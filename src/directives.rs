pub fn typed_at(text: &str, cursor: usize) -> Option<usize> {
    let before = &text[..cursor];
    let at = before.rfind('@')?;
    let name = &before[at + 1..];
    if !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return None;
    }
    let prev = before[..at].chars().last();
    if prev.is_some_and(|c| c.is_alphanumeric() || c == '_' || c == '@' || c == '.') {
        return None;
    }
    Some(at)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_directive_prefixes() {
        assert_eq!(typed_at("<p>\n    @fore", 13), Some(8));
        assert_eq!(typed_at("mail@exam", 9), None);
        assert_eq!(typed_at("@if(x) foo", 10), None);
    }
}
